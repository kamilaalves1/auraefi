const isBuildPhase = process.env.NEXT_PHASE === 'phase-production-build'
const isTestMode = process.env.MISSION_CONTROL_TEST_MODE === '1'

/** Initialize schema and seed data. Called once at startup. */
let _initialized = false
let _initPromise: Promise<void> | null = null

export function initializeDatabase(): Promise<void> {
  if (_initialized) return Promise.resolve()
  if (_initPromise) return _initPromise

  _initPromise = (async () => {
    ensureAutoGeneratedCredentials()
    const pool = getPool()
    const conn = await pool.getConnection()
    try {
      await runMigrations(conn)
      await seedAdminUserFromEnv()
      _initialized = true
      if (!isBuildPhase) logger.info('Database migrations applied successfully')

      if (!isBuildPhase && !isTestMode) {
        import('./webhooks').then(({ initWebhookListener }) => initWebhookListener()).catch(() => {})
        import('./scheduler').then(({ initScheduler }) => initScheduler()).catch(() => {})
      }
    } finally {
      conn.release()
    }
  })()

  _initPromise.catch(err => {
    logger.error({ err }, 'Failed to initialize database')
    _initPromise = null
  })

  return _initPromise
}

// Built-in admin credentials
export const BUILTIN_ADMIN_USERNAME = 'admin'
export const BUILTIN_ADMIN_PASSWORD = 'admin'

export function resolveSeedAuthPassword(env: NodeJS.ProcessEnv = process.env): string | null {
  const b64 = env.AUTH_PASS_B64
  if (b64 && b64.trim().length > 0) {
    const normalized = b64.trim()
    const base64Pattern = /^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/
    if (!base64Pattern.test(normalized)) {
      logger.warn('AUTH_PASS_B64 is not valid base64; falling back to AUTH_PASS')
      return env.AUTH_PASS || null
    }
    try {
      const decoded = Buffer.from(normalized, 'base64').toString('utf8')
      const canonical = Buffer.from(decoded, 'utf8').toString('base64')
      if (canonical !== normalized) {
        logger.warn('AUTH_PASS_B64 failed base64 verification; falling back to AUTH_PASS')
        return env.AUTH_PASS || null
      }
      if (decoded.length > 0) return decoded
      logger.warn('AUTH_PASS_B64 decoded to empty; falling back to AUTH_PASS')
    } catch {
      logger.warn('AUTH_PASS_B64 is not valid base64; falling back to AUTH_PASS')
    }
  }
  return env.AUTH_PASS || null
}

async function ensureBuiltInAdmin(): Promise<void> {
  if (isBuildPhase || isTestMode) return
  const existing = await dbGetOne<{ id: number }>(
    'SELECT id FROM users WHERE username = ?',
    [BUILTIN_ADMIN_USERNAME]
  )
  if (!existing) {
    const hash = hashPassword(BUILTIN_ADMIN_PASSWORD)
    await dbRun(
      'INSERT INTO users (username, display_name, password_hash, role) VALUES (?, ?, ?, ?)',
      [BUILTIN_ADMIN_USERNAME, 'Admin', hash, 'admin']
    )
    logger.warn('Built-in admin account created with default password — change it immediately at /settings/users')
  } else {
    logger.info(`Built-in admin account exists: ${BUILTIN_ADMIN_USERNAME}`)
  }
}

async function seedAdminUserFromEnv(): Promise<void> {
  await ensureBuiltInAdmin()
}

export async function needsFirstTimeSetup(): Promise<boolean> {
  try {
    const row = await dbGetOne<{ count: number }>('SELECT COUNT(*) as count FROM users')
    return (row?.count ?? 0) === 0
  } catch {
    return false
  }
}

export async function closeDatabase(): Promise<void> {
  await closePool()
}

