// ── Async DB helpers ──────────────────────────────────────────────────────────

export const db_helpers = {
  logActivity: async (
    type: string,
    entity_type: string,
    entity_id: number,
    actor: string,
    description: string,
    data?: any,
    workspaceId: number = 1
  ): Promise<void> => {
    const result = await dbRun(
      `INSERT INTO activities (type, entity_type, entity_id, actor, description, data, workspace_id)
       VALUES (?, ?, ?, ?, ?, ?, ?)`,
      [type, entity_type, entity_id, actor, description, data ? JSON.stringify(data) : null, workspaceId]
    )
    eventBus.broadcast('activity.created', {
      id: result.insertId, type, entity_type, entity_id, actor, description,
      data: data || null,
      created_at: Math.floor(Date.now() / 1000),
      workspace_id: workspaceId,
    })
  },

  createNotification: async (
    recipient: string,
    type: string,
    title: string,
    message: string,
    source_type?: string,
    source_id?: number,
    workspaceId: number = 1
  ): Promise<{ insertId: number }> => {
    const result = await dbRun(
      `INSERT INTO notifications (recipient, type, title, message, source_type, source_id, workspace_id)
       VALUES (?, ?, ?, ?, ?, ?, ?)`,
      [recipient, type, title, message, source_type, source_id, workspaceId]
    )
    eventBus.broadcast('notification.created', {
      id: result.insertId, recipient, type, title, message,
      source_type: source_type || null, source_id: source_id || null,
      created_at: Math.floor(Date.now() / 1000),
      workspace_id: workspaceId,
    })
    return result
  },

  parseMentions: (text: string): string[] => {
    return parseMentionTokens(text)
  },

  updateAgentStatus: async (
    agentName: string,
    status: Agent['status'],
    activity?: string,
    workspaceId: number = 1
  ): Promise<void> => {
    const now = Math.floor(Date.now() / 1000)
    const agent = await dbGetOne<{ id: number }>(
      'SELECT id FROM agents WHERE name = ? AND workspace_id = ?',
      [agentName, workspaceId]
    )
    await dbRun(
      `UPDATE agents SET status = ?, last_seen = ?, last_activity = ?, updated_at = ?
       WHERE name = ? AND workspace_id = ?`,
      [status, now, activity, now, agentName, workspaceId]
    )
    if (agent) {
      eventBus.broadcast('agent.status_changed', {
        id: agent.id, name: agentName, status,
        last_seen: now, last_activity: activity || null,
      })
    }
    db_helpers.logActivity(
      'agent_status_change', 'agent', agent?.id || 0, agentName,
      `Agent status changed to ${status}`, { status, activity }, workspaceId
    ).catch(() => {})
  },

  getRecentActivities: async (limit: number = 50): Promise<Activity[]> => {
    return dbGetAll<Activity>(`SELECT * FROM activities ORDER BY created_at DESC LIMIT ?`, [limit])
  },

  getUnreadNotifications: async (recipient: string, workspaceId: number = 1): Promise<Notification[]> => {
    return dbGetAll<Notification>(
      `SELECT * FROM notifications WHERE recipient = ? AND read_at IS NULL AND workspace_id = ? ORDER BY created_at DESC`,
      [recipient, workspaceId]
    )
  },

  markNotificationRead: async (notificationId: number, workspaceId: number = 1): Promise<void> => {
    await dbRun(
      `UPDATE notifications SET read_at = ? WHERE id = ? AND workspace_id = ?`,
      [Math.floor(Date.now() / 1000), notificationId, workspaceId]
    )
  },

  ensureTaskSubscription: async (taskId: number, agentName: string, workspaceId: number = 1): Promise<void> => {
    if (!agentName) return
    await dbRun(
      `INSERT IGNORE INTO task_subscriptions (task_id, agent_name)
       SELECT t.id, ? FROM tasks t WHERE t.id = ? AND t.workspace_id = ?`,
      [agentName, taskId, workspaceId]
    )
  },

  getTaskSubscribers: async (taskId: number, workspaceId: number = 1): Promise<string[]> => {
    const rows = await dbGetAll<{ agent_name: string }>(
      `SELECT ts.agent_name FROM task_subscriptions ts
       JOIN tasks t ON t.id = ts.task_id
       WHERE ts.task_id = ? AND t.workspace_id = ?`,
      [taskId, workspaceId]
    )
    return rows.map(r => r.agent_name)
  },
}

export async function logAuditEvent(event: {
  action: string
  actor: string
  actor_id?: number
  target_type?: string
  target_id?: number
  detail?: any
  ip_address?: string
  user_agent?: string
}): Promise<void> {
  await dbRun(
    `INSERT INTO audit_log (action, actor, actor_id, target_type, target_id, detail, ip_address, user_agent)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
    [
      event.action, event.actor,
      event.actor_id ?? null, event.target_type ?? null, event.target_id ?? null,
      event.detail ? JSON.stringify(event.detail) : null,
      event.ip_address ?? null, event.user_agent ?? null,
    ]
  )
  const securityEvents = ['login_failed', 'user_created', 'user_deleted', 'password_change']
  if (securityEvents.includes(event.action)) {
    eventBus.broadcast('audit.security', {
      action: event.action, actor: event.actor,
      target_type: event.target_type ?? null, target_id: event.target_id ?? null,
      timestamp: Math.floor(Date.now() / 1000),
    })
  }
}

export async function appendProvisionEvent(event: {
  job_id: number
  level?: 'info' | 'warn' | 'error'
  step_key?: string
  message: string
  data?: any
}): Promise<void> {
  await dbRun(
    `INSERT INTO provision_events (job_id, level, step_key, message, data) VALUES (?, ?, ?, ?, ?)`,
    [event.job_id, event.level || 'info', event.step_key ?? null, event.message,
     event.data ? JSON.stringify(event.data) : null]
  )
}

